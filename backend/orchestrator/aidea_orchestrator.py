# ================================================================
# AIDEA ORCHESTRATOR
# ================================================================

class AIDEAOrchestrator:

    def __init__(self):

        self.engines = {}

    # ============================================================
    # REGISTER ENGINE
    # ============================================================

    def register(

        self,

        name,

        engine
    ):

        self.engines[name] = engine

    # ============================================================
    # GET ENGINE
    # ============================================================

    def get(self, name):

        return self.engines.get(name)

    # ============================================================
    # LIST ENGINES
    # ============================================================

    def list_engines(self):

        return list(self.engines.keys())